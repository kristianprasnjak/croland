    import csv, re
    put = '/home/claude/w/croland-de/sucelje-de.tsv'
    rows = list(csv.DictReader(open(put, encoding='utf-8'), delimiter='\t'))
    n = 0
    for r in rows:
        if not r['de'] and r['en'] in DE:
            assert sorted(re.findall(r'%\d', r['en'])) == sorted(re.findall(r'%\d', DE[r['en']])), r['en']
            r['de'] = DE[r['en']]; n += 1
    fali = [r['en'] for r in rows if not r['de']]
    with open(put, 'w', encoding='utf-8', newline='') as fo:
        w = csv.DictWriter(fo, fieldnames=['en', 'de', 'izvor', 'redak'], delimiter='\t', lineterminator='\n')
        w.writeheader(); w.writerows(rows)
    print('upisano', n, 'fali', fali, 'neiskoristeno', [k for k in DE if k not in {r['en'] for r in rows}])
